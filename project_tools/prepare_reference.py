"""Prepare canonical Markdown for Astro without MkDocs.

Python-Markdown + PyMdown retain the documented Markdown dialect and heading IDs.
This is presentation only: method_docs projects existing owner-produced fixtures.
Every prepared page and asset is tied to the current complete source identity.
"""

from __future__ import annotations

import argparse
import hashlib
import html
import json
import posixpath
import shutil
from html.parser import HTMLParser
from pathlib import Path
from types import SimpleNamespace
from urllib.parse import urlsplit, urlunsplit

import markdown

try:
    from .method_docs import on_page_markdown
    from .site_identity import ROOT, input_identity
except ImportError:
    from method_docs import on_page_markdown
    from site_identity import ROOT, input_identity
BASE = "/quant-backtest-engine/"


def local_url(value, source):
    u = urlsplit(value)
    if u.scheme or u.netloc or not u.path or u.path.startswith("/"):
        return value
    path = posixpath.normpath(posixpath.join(posixpath.dirname(source), u.path))
    if path.startswith("../"):
        raise ValueError(f"link escapes docs: {source}: {value}")
    if path.endswith(".md"):
        path = "" if path == "index.md" else path[:-3] + "/"
    return urlunsplit(("", "", BASE + path, u.query, u.fragment))


class Rewrite(HTMLParser):
    def __init__(self, source):
        super().__init__(convert_charrefs=False)
        self.source, self.parts = source, []

    def handle_starttag(self, tag, attrs):
        attrs = [
            (k, local_url(v, self.source) if k in {"href", "src"} and v else v)
            for k, v in attrs
        ]
        self.parts.append(
            "<"
            + tag
            + "".join(
                " " + k
                if v is None
                else " " + k + '="' + html.escape(v, quote=True) + '"'
                for k, v in attrs
            )
            + ">"
        )

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)

    def handle_endtag(self, tag):
        self.parts.append("</" + tag + ">")

    def handle_data(self, data):
        self.parts.append(data)

    def handle_entityref(self, name):
        self.parts.append("&" + name + ";")

    def handle_charref(self, name):
        self.parts.append("&#" + name + ";")

    def handle_comment(self, data):
        self.parts.append("<!--" + data + "-->")


def render_markdown(text, source):
    expanded = on_page_markdown(
        text, SimpleNamespace(file=SimpleNamespace(src_uri=source)), None, None
    )
    rendered = markdown.markdown(
        expanded,
        extensions=[
            "tables",
            "admonition",
            "attr_list",
            "pymdownx.details",
            "pymdownx.superfences",
            "toc",
        ],
        extension_configs={"toc": {"permalink": True}},
    )
    parser = Rewrite(source)
    parser.feed(rendered)
    return "".join(parser.parts)


class Metadata(HTMLParser):
    def __init__(self):
        super().__init__()
        self.ids = []
        self.text = []

    def handle_starttag(self, tag, attrs):
        value = dict(attrs).get("id")
        if value:
            self.ids.append(value)

    def handle_data(self, data):
        self.text.append(data)


def prepare(output):
    if output.exists() and any(output.iterdir()):
        raise ValueError("reference output must be fresh")
    output.mkdir(parents=True, exist_ok=True)
    routes = json.loads((ROOT / "docs/site/route-ownership.json").read_text())
    legacy = json.loads((ROOT / "docs/site/legacy-route-anchors.json").read_text())[
        "html"
    ]
    names = routes.get("reference_html", routes.get("mkdocs_html", []))
    pages = []
    docs = []
    fragments = {}
    for name in names:
        if name == "404.html":
            continue
        source = (
            "index.md"
            if name == "index.html"
            else name.removesuffix("/index.html") + ".md"
        )
        path = ROOT / "docs" / source
        if not path.is_file():
            raise ValueError(f"missing canonical Markdown: {source}")
        content = render_markdown(path.read_text(), source)
        meta = Metadata()
        meta.feed(content)
        missing_headings = set(legacy.get(name, {}).get("heading_ids", [])) - set(
            meta.ids
        )
        if missing_headings:
            raise ValueError(f"legacy heading IDs changed: {name}: {missing_headings}")
        if len(meta.ids) != len(set(meta.ids)):
            raise ValueError(f"duplicate article IDs: {source}")
        # Retain old shell/control fragments as visible, non-interactive compatibility
        # targets. Content heading IDs are generated by the original Markdown dialect.
        aliases = [x for x in legacy.get(name, {}).get("ids", []) if x not in meta.ids]
        content += (
            '<div class="reference-legacy-anchors" aria-hidden="true">'
            + "".join(
                '<span id="'
                + html.escape(x, quote=True)
                + '" class="reference-anchor"></span>'
                for x in aliases
            )
            + "</div>"
        )
        slug = "" if name == "index.html" else name.removesuffix("/index.html")
        locale = "zh-CN" if ".zh-CN" in source else "en"
        title = next(
            (
                line.lstrip("# ").strip()
                for line in path.read_text().splitlines()
                if line.startswith("# ")
            ),
            source,
        )
        target = output / "pages" / name.replace("/index.html", ".html")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
        entry = {
            "route": slug,
            "file": name,
            "source": source,
            "fragment": target.relative_to(output).as_posix(),
            "sha256": hashlib.sha256(content.encode()).hexdigest(),
            "title": title,
            "locale": locale,
        }
        pages.append(entry)
        if source in {"index.md", "index.zh-CN.md"}:
            fragments[locale] = entry
        docs.append(
            {
                "location": BASE + (slug + "/" if slug else ""),
                "title": title,
                "text": " ".join(meta.text),
                "locale": locale,
            }
        )
    assets = output / "public"
    assets.mkdir()
    for directory in ["assets", "javascripts", "stylesheets", "site"]:
        shutil.copytree(ROOT / "docs" / directory, assets / directory)
    (assets / "migration").mkdir()
    shutil.copyfile(
        ROOT / "docs/migration/reusable-ownership.json",
        assets / "migration/reusable-ownership.json",
    )
    (assets / ".nojekyll").touch()
    (assets / "search").mkdir()
    (assets / "search/search_index.json").write_text(
        json.dumps({"docs": docs}, ensure_ascii=False)
    )
    (output / "receipt.json").write_text(
        json.dumps(
            {
                "schema": "engine-reference-markdown.v1",
                "identity": input_identity(),
                "pages": pages,
                "fragments": fragments,
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n"
    )


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--output", required=True, type=Path)
    prepare(p.parse_args().output)
